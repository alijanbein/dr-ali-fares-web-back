from sqlalchemy import JSON, Boolean, Column, DateTime, Float, Integer, String, Text

from database import Base


class BookingRequest(Base):
    """A patient's appointment request from the doctor's website: their details,
    the pre-visit questionnaire and when they would like to come. It stays a
    request until the secretary confirms a time with the patient."""
    __tablename__ = "doctor_booking_requests"

    id = Column(String, primary_key=True)
    # Short code the patient quotes to the secretary on WhatsApp or by phone.
    reference = Column(String, nullable=False, unique=True, index=True)
    # Generated by the browser, so retrying after a lost response can't create
    # a second request.
    submissionId = Column(String, nullable=False, unique=True)
    status = Column(String, nullable=False, default="new", index=True)
    createdAt = Column(DateTime(timezone=True), nullable=False, index=True)
    updatedAt = Column(DateTime(timezone=True), nullable=False)
    language = Column(String, nullable=False)

    name = Column(String, nullable=False)
    age = Column(Integer, nullable=False)
    gender = Column(String, nullable=False)
    phone = Column(String, nullable=False)
    contactMethod = Column(String, nullable=False)

    bodyArea = Column(String, nullable=False)
    side = Column(String, nullable=True)
    chiefComplaint = Column(Text, nullable=False)
    onset = Column(String, nullable=False)
    mechanism = Column(String, nullable=False)
    history = Column(Text, nullable=True)

    redFlags = Column(JSON, nullable=False)
    urgent = Column(Boolean, nullable=False, default=False, index=True)

    # Same shape as the hospital's Assessment, so a request can later become a
    # Patient + Encounter + Assessment there without converting anything.
    promName = Column(String, nullable=True)
    promCode = Column(String, nullable=True)
    answers = Column(JSON, nullable=False)
    painScore = Column(Float, nullable=True)
    score = Column(Integer, nullable=True)
    maxScore = Column(Integer, nullable=True)
    finalScore = Column(Float, nullable=True)
    scoreDirection = Column(String, nullable=True)
    interpretation = Column(JSON, nullable=True)

    preferredDate = Column(String, nullable=True)
    preferredTime = Column(String, nullable=False)
    notes = Column(Text, nullable=True)

    secretaryNote = Column(Text, nullable=True)
